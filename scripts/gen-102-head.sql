-- =====================================================================
-- 102  Mess routine menu, 3 Oct 2026.
--   A routine menu is one week (Monday to Sunday) of breakfast, lunch, evening snacks and dinner for one kind of
--   student: Boys or Girls hostel, South Indian, North Indian or International food by country (apartments and
--   overseas students), Veg or Non-veg. The administrator prepares a menu as a draft; the Chief Warden approves it,
--   and the approved menu replaces the one before it. A menu may be for one mess only, or for every mess.
--   Each student's food choice (food style, veg or non-veg, country) lives on the mess subscription; the menu a
--   student sees is the approved one that fits the hostel they live in and that choice.
--   This file is generated by scripts/gen-102-menus.py (tables from gen-102-head.sql, then the starter menus).
-- =====================================================================

ALTER TABLE hostel.hostel_profile ADD COLUMN IF NOT EXISTS accommodation_type varchar(10) NOT NULL DEFAULT 'Hostel'
  CHECK (accommodation_type IN ('Hostel', 'Apartment'));
COMMENT ON COLUMN hostel.hostel_profile.accommodation_type IS 'Hostel (shared rooms, common mess) or Apartment (overseas students; food by country)';

-- ---------- the student's food choice ----------
ALTER TABLE hostel.mess_subscription
  ADD COLUMN IF NOT EXISTS region varchar(15) CHECK (region IN ('South', 'North', 'International')),
  ADD COLUMN IF NOT EXISTS diet varchar(10) CHECK (diet IN ('Veg', 'Non_Veg')),
  ADD COLUMN IF NOT EXISTS country varchar(60);
ALTER TABLE hostel.mess_subscription ADD CONSTRAINT ck_mess_sub_country CHECK (region IS DISTINCT FROM 'International' OR country IS NOT NULL);
COMMENT ON COLUMN hostel.mess_subscription.region IS 'Food style: South, North, or International (then country says which)';
COMMENT ON COLUMN hostel.mess_subscription.diet IS 'Veg or Non_Veg';
UPDATE hostel.mess_subscription SET
  region = CASE WHEN cuisine = 'North_Indian' THEN 'North' ELSE 'South' END,
  diet = CASE WHEN cuisine = 'Non_Veg' THEN 'Non_Veg' ELSE 'Veg' END
 WHERE region IS NULL;

-- ---------- routine menus ----------
CREATE TABLE hostel.menu_cycle (
  cycle_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  hostel_gender   varchar(10) NOT NULL CHECK (hostel_gender IN ('Boys', 'Girls', 'Any')),
  region          varchar(15) NOT NULL CHECK (region IN ('South', 'North', 'International')),
  country         varchar(60),
  diet            varchar(10) NOT NULL CHECK (diet IN ('Veg', 'Non_Veg')),
  mess_id         bigint REFERENCES hostel.mess_master(mess_id),
  title           varchar(120) NOT NULL,
  notes           text,
  status          varchar(10) NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft', 'Approved', 'Retired')),
  effective_from  date NOT NULL DEFAULT current_date,
  based_on        bigint REFERENCES hostel.menu_cycle(cycle_id),
  approved_by     varchar(20) REFERENCES ref.staff_master(staff_id),
  approved_on     timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  created_by      varchar(20),
  updated_at      timestamptz,
  updated_by      varchar(20),
  CONSTRAINT ck_menu_cycle_country CHECK ((region = 'International') = (country IS NOT NULL)),
  CONSTRAINT ck_menu_cycle_approved CHECK (status = 'Draft' OR approved_on IS NOT NULL)
);
COMMENT ON TABLE hostel.menu_cycle IS 'A weekly routine menu for one hostel type, food style (or country) and diet; Draft until the Chief Warden approves';
-- one approved menu per kind of student (and mess)
CREATE UNIQUE INDEX ux_menu_cycle_live ON hostel.menu_cycle (hostel_gender, region, coalesce(country, ''), diet, coalesce(mess_id, 0)) WHERE status = 'Approved';
-- one draft at a time per kind of student, so two people do not prepare competing versions
CREATE UNIQUE INDEX ux_menu_cycle_draft ON hostel.menu_cycle (hostel_gender, region, coalesce(country, ''), diet, coalesce(mess_id, 0)) WHERE status = 'Draft';

CREATE TABLE hostel.menu_cycle_item (
  item_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cycle_id    bigint NOT NULL REFERENCES hostel.menu_cycle(cycle_id) ON DELETE CASCADE,
  day_no      smallint NOT NULL CHECK (day_no BETWEEN 1 AND 7),
  meal        hostel.meal_slot NOT NULL,
  dishes      text NOT NULL CHECK (length(trim(dishes)) > 0),
  updated_at  timestamptz,
  updated_by  varchar(20),
  UNIQUE (cycle_id, day_no, meal)
);
COMMENT ON TABLE hostel.menu_cycle_item IS 'One meal of a routine menu: day 1 = Monday ... 7 = Sunday';

CREATE TRIGGER trg_touch_updated_at BEFORE UPDATE ON hostel.menu_cycle FOR EACH ROW EXECUTE FUNCTION shared.fn_touch_updated_at();
CREATE TRIGGER trg_touch_updated_at BEFORE UPDATE ON hostel.menu_cycle_item FOR EACH ROW EXECUTE FUNCTION shared.fn_touch_updated_at();
CREATE TRIGGER trg_audit_menu_cycle AFTER INSERT OR UPDATE OR DELETE ON hostel.menu_cycle FOR EACH ROW EXECUTE FUNCTION shared.fn_audit_row('cycle_id');
CREATE TRIGGER trg_audit_menu_cycle_item AFTER UPDATE OR DELETE ON hostel.menu_cycle_item FOR EACH ROW EXECUTE FUNCTION shared.fn_audit_row('item_id');

-- An approved menu is not edited in place: the change is made on a draft, which the Chief Warden approves.
CREATE OR REPLACE FUNCTION hostel.fn_menu_item_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE st varchar;
BEGIN
  SELECT status INTO st FROM hostel.menu_cycle WHERE cycle_id = coalesce(NEW.cycle_id, OLD.cycle_id);
  IF st <> 'Draft' AND TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'This menu is %; change a draft of it instead', lower(st) USING ERRCODE = 'P0001';
  END IF;
  RETURN coalesce(NEW, OLD);
END $$;
CREATE TRIGGER trg_menu_item_guard BEFORE UPDATE OR DELETE ON hostel.menu_cycle_item FOR EACH ROW EXECUTE FUNCTION hostel.fn_menu_item_guard();

-- Approving a draft retires the menu it replaces, in the same step.
CREATE OR REPLACE FUNCTION hostel.fn_menu_cycle_approve() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'Approved' AND OLD.status = 'Draft' THEN
    IF (SELECT count(*) FROM hostel.menu_cycle_item WHERE cycle_id = NEW.cycle_id) < 28 THEN
      RAISE EXCEPTION 'Fill all 28 meals (7 days x 4) before approving' USING ERRCODE = 'P0001';
    END IF;
    UPDATE hostel.menu_cycle SET status = 'Retired', updated_by = NEW.approved_by
     WHERE status = 'Approved' AND cycle_id <> NEW.cycle_id AND hostel_gender = NEW.hostel_gender AND region = NEW.region
       AND country IS NOT DISTINCT FROM NEW.country AND diet = NEW.diet AND mess_id IS NOT DISTINCT FROM NEW.mess_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_menu_cycle_approve BEFORE UPDATE OF status ON hostel.menu_cycle FOR EACH ROW EXECUTE FUNCTION hostel.fn_menu_cycle_approve();

-- ---------- which menu a student eats ----------
-- The student's hostel (Boys or Girls), mess and food choice, and the approved menu that fits best:
-- a menu for the student's own mess before an all-mess one, the hostel's own gender before 'Any'.
CREATE OR REPLACE VIEW hostel.v_student_menu AS
WITH s AS (
  SELECT a.student_id, b.facility_id, b.hostel_code, hp.hostel_gender::text AS hostel_gender, hp.accommodation_type,
         coalesce(ms.mess_id, hp.default_mess_id) AS mess_id, ms.subscription_id,
         coalesce(ms.region, 'South') AS region, coalesce(ms.diet, 'Veg') AS diet, ms.country, sm.nationality
    FROM hostel.hostel_allocation a
    JOIN hostel.v_bed b ON b.subspace_id = a.subspace_id
    JOIN hostel.hostel_profile hp ON hp.facility_id = b.facility_id
    JOIN ref.student_master sm ON sm.student_id = a.student_id
    LEFT JOIN LATERAL (
      SELECT x.* FROM hostel.mess_subscription x
       WHERE x.student_id = a.student_id AND x.status = 'Active'
       ORDER BY (x.academic_year = (SELECT academic_year FROM hostel.academic_year WHERE is_current)) DESC, x.from_date DESC LIMIT 1) ms ON true
   WHERE a.status = 'Active' AND a.occupant_type = 'Student')
SELECT DISTINCT ON (s.student_id) s.*, c.cycle_id, c.title AS menu_title
  FROM s LEFT JOIN hostel.menu_cycle c
    ON c.status = 'Approved' AND c.effective_from <= current_date AND c.region = s.region AND c.diet = s.diet
   AND c.country IS NOT DISTINCT FROM (CASE WHEN s.region = 'International' THEN s.country END)
   AND c.hostel_gender IN (s.hostel_gender, 'Any') AND (c.mess_id IS NULL OR c.mess_id = s.mess_id)
 ORDER BY s.student_id, (c.mess_id IS NOT NULL) DESC, (c.hostel_gender = s.hostel_gender) DESC, c.effective_from DESC;
COMMENT ON VIEW hostel.v_student_menu IS 'Each resident, their food choice and the approved routine menu that fits them (cycle_id NULL = no menu yet)';
