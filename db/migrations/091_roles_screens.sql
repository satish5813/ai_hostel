-- ELE-03: Hostel Accounts enters a tariff (X); it takes effect only once the Pro-VC Finance approves it (A)
CREATE OR REPLACE VIEW hostel.v_meter_position AS
SELECT rm.meter_id, rm.meter_no, rm.space_id, s.space_code, rp.room_type_id,
       lr.reading_kwh AS last_reading, lr.reading_at AS last_reading_at,
       coalesce(mo.reading_kwh, fm.reading_kwh) AS month_opening,
       lr.reading_kwh - coalesce(mo.reading_kwh, fm.reading_kwh) AS units_this_month,
       t.included_units_per_month,
       rc.units AS recharged_this_month,
       coalesce(t.included_units_per_month, 0) + rc.units - coalesce(lr.reading_kwh - coalesce(mo.reading_kwh, fm.reading_kwh), 0) AS units_left,
       t.rate_per_unit
FROM hostel.room_meter rm
JOIN infra.space s ON s.space_id = rm.space_id
JOIN hostel.room_profile rp ON rp.space_id = rm.space_id
LEFT JOIN hostel.electricity_tariff t ON t.room_type_id = rp.room_type_id AND t.approved_by IS NOT NULL
     AND current_date >= t.effective_from AND (t.effective_to IS NULL OR current_date <= t.effective_to)
LEFT JOIN LATERAL (SELECT reading_kwh, reading_at FROM hostel.meter_reading r WHERE r.meter_id = rm.meter_id ORDER BY reading_at DESC LIMIT 1) lr ON true
LEFT JOIN LATERAL (SELECT reading_kwh FROM hostel.meter_reading r WHERE r.meter_id = rm.meter_id AND r.reading_at <  date_trunc('month', now()) ORDER BY reading_at DESC LIMIT 1) mo ON true
LEFT JOIN LATERAL (SELECT reading_kwh FROM hostel.meter_reading r WHERE r.meter_id = rm.meter_id AND r.reading_at >= date_trunc('month', now()) ORDER BY reading_at ASC  LIMIT 1) fm ON true
LEFT JOIN LATERAL (SELECT coalesce(sum(units_credited), 0) AS units FROM hostel.meter_recharge mr WHERE mr.meter_id = rm.meter_id AND mr.status IN ('Paid','Credited') AND date_trunc('month', mr.created_at) = date_trunc('month', now())) rc ON true
WHERE rm.status = 'Active';

-- RPT-07 Occupancy, fees and dues: one row per hostel (beds, collections, overdue)
CREATE OR REPLACE VIEW hostel.v_rpt_occupancy_fees_dues AS
SELECT v.facility_id, v.hostel_name, v.hostel_code,
       sum(v.total_beds) AS total_beds, sum(v.occupied_beds) AS occupied_beds, sum(v.vacant_beds) AS vacant_beds, sum(v.held_beds) AS held_beds,
       (SELECT count(*) FROM hostel.hostel_registration r WHERE r.facility_id = v.facility_id AND r.status NOT IN ('Cancelled','Vacated')) AS registrations,
       (SELECT coalesce(sum(d.amount_due), 0)  FROM hostel.fee_demand d JOIN hostel.hostel_registration r ON r.student_id = d.student_id AND r.facility_id = v.facility_id) AS demanded,
       (SELECT coalesce(sum(d.amount_paid), 0) FROM hostel.fee_demand d JOIN hostel.hostel_registration r ON r.student_id = d.student_id AND r.facility_id = v.facility_id) AS collected,
       (SELECT coalesce(sum(d.amount_due - d.amount_paid), 0) FROM hostel.fee_demand d JOIN hostel.hostel_registration r ON r.student_id = d.student_id AND r.facility_id = v.facility_id WHERE d.status = 'Overdue') AS overdue,
       (SELECT count(DISTINCT d.student_id) FROM hostel.fee_demand d JOIN hostel.hostel_registration r ON r.student_id = d.student_id AND r.facility_id = v.facility_id WHERE d.status = 'Overdue') AS students_overdue
FROM hostel.v_vacancy v
GROUP BY 1, 2, 3;

