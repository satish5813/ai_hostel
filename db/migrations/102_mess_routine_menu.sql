-- =====================================================================
-- 102  Mess routine menu, 3 Oct 2026.
--   A routine menu is one week (Monday to Sunday) of breakfast, lunch, evening snacks and dinner for one kind of
--   student: Boys or Girls hostel, South Indian, North Indian or International food by country (apartments and
--   overseas students), Veg or Non-veg. The administrator prepares a menu as a draft; the Chief Warden approves it,
--   and the approved menu replaces the one before it. A menu may be for one mess only, or for every mess.
--   Each student's food choice (food style, veg or non-veg, country) lives on the mess subscription; the menu a
--   student sees is the approved one that fits the hostel they live in and that choice.
--   This file is generated by scripts/gen-102-menus.py (tables from gen-102-head.sql, then the starter menus).
-- =====================================================================

ALTER TABLE hostel.hostel_profile ADD COLUMN IF NOT EXISTS accommodation_type varchar(10) NOT NULL DEFAULT 'Hostel'
  CHECK (accommodation_type IN ('Hostel', 'Apartment'));
COMMENT ON COLUMN hostel.hostel_profile.accommodation_type IS 'Hostel (shared rooms, common mess) or Apartment (overseas students; food by country)';

-- ---------- the student's food choice ----------
ALTER TABLE hostel.mess_subscription
  ADD COLUMN IF NOT EXISTS region varchar(15) CHECK (region IN ('South', 'North', 'International')),
  ADD COLUMN IF NOT EXISTS diet varchar(10) CHECK (diet IN ('Veg', 'Non_Veg')),
  ADD COLUMN IF NOT EXISTS country varchar(60);
ALTER TABLE hostel.mess_subscription ADD CONSTRAINT ck_mess_sub_country CHECK (region IS DISTINCT FROM 'International' OR country IS NOT NULL);
COMMENT ON COLUMN hostel.mess_subscription.region IS 'Food style: South, North, or International (then country says which)';
COMMENT ON COLUMN hostel.mess_subscription.diet IS 'Veg or Non_Veg';
UPDATE hostel.mess_subscription SET
  region = CASE WHEN cuisine = 'North_Indian' THEN 'North' ELSE 'South' END,
  diet = CASE WHEN cuisine = 'Non_Veg' THEN 'Non_Veg' ELSE 'Veg' END
 WHERE region IS NULL;

-- ---------- routine menus ----------
CREATE TABLE hostel.menu_cycle (
  cycle_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  hostel_gender   varchar(10) NOT NULL CHECK (hostel_gender IN ('Boys', 'Girls', 'Any')),
  region          varchar(15) NOT NULL CHECK (region IN ('South', 'North', 'International')),
  country         varchar(60),
  diet            varchar(10) NOT NULL CHECK (diet IN ('Veg', 'Non_Veg')),
  mess_id         bigint REFERENCES hostel.mess_master(mess_id),
  title           varchar(120) NOT NULL,
  notes           text,
  status          varchar(10) NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft', 'Approved', 'Retired')),
  effective_from  date NOT NULL DEFAULT current_date,
  based_on        bigint REFERENCES hostel.menu_cycle(cycle_id),
  approved_by     varchar(20) REFERENCES ref.staff_master(staff_id),
  approved_on     timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  created_by      varchar(20),
  updated_at      timestamptz,
  updated_by      varchar(20),
  CONSTRAINT ck_menu_cycle_country CHECK ((region = 'International') = (country IS NOT NULL)),
  CONSTRAINT ck_menu_cycle_approved CHECK (status = 'Draft' OR approved_on IS NOT NULL)
);
COMMENT ON TABLE hostel.menu_cycle IS 'A weekly routine menu for one hostel type, food style (or country) and diet; Draft until the Chief Warden approves';
-- one approved menu per kind of student (and mess)
CREATE UNIQUE INDEX ux_menu_cycle_live ON hostel.menu_cycle (hostel_gender, region, coalesce(country, ''), diet, coalesce(mess_id, 0)) WHERE status = 'Approved';
-- one draft at a time per kind of student, so two people do not prepare competing versions
CREATE UNIQUE INDEX ux_menu_cycle_draft ON hostel.menu_cycle (hostel_gender, region, coalesce(country, ''), diet, coalesce(mess_id, 0)) WHERE status = 'Draft';

CREATE TABLE hostel.menu_cycle_item (
  item_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cycle_id    bigint NOT NULL REFERENCES hostel.menu_cycle(cycle_id) ON DELETE CASCADE,
  day_no      smallint NOT NULL CHECK (day_no BETWEEN 1 AND 7),
  meal        hostel.meal_slot NOT NULL,
  dishes      text NOT NULL CHECK (length(trim(dishes)) > 0),
  updated_at  timestamptz,
  updated_by  varchar(20),
  UNIQUE (cycle_id, day_no, meal)
);
COMMENT ON TABLE hostel.menu_cycle_item IS 'One meal of a routine menu: day 1 = Monday ... 7 = Sunday';

